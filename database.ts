import { AsyncLocalStorage } from "node:async_hooks";
import pg, { type PoolClient, type QueryResult } from "pg";

const { Pool, types } = pg;
types.setTypeParser(20, (value) => Number(value));
types.setTypeParser(1700, (value) => Number(value));

const databaseUrl = process.env.DATABASE_URL?.trim();
if (!databaseUrl) throw new Error("DATABASE_URL não configurada. Configure o PostgreSQL no ambiente do servidor.");

export const pool = new Pool({
  connectionString: databaseUrl,
  max: Number(process.env.PG_POOL_MAX || 10),
  idleTimeoutMillis: 30_000,
  connectionTimeoutMillis: 10_000,
  application_name: "mwe-harmonize",
  ssl: { rejectUnauthorized: false },
});

const transactionContext = new AsyncLocalStorage<PoolClient>();

function postgresPlaceholders(sql: string) {
  let output = "";
  let parameter = 0;
  let quote: "'" | '"' | null = null;
  for (let i = 0; i < sql.length; i++) {
    const char = sql[i];
    if (quote) {
      output += char;
      if (char === quote && sql[i + 1] === quote) output += sql[++i];
      else if (char === quote) quote = null;
      continue;
    }
    if (char === "'" || char === '"') {
      quote = char;
      output += char;
    } else if (char === "?") output += `$${++parameter}`;
    else output += char;
  }
  return output;
}

const normalizeRow = (row: any) => {
  if (!row) return row;
  if (Object.hasOwn(row, "novoseventos")) {
    row.novosEventos = row.novoseventos;
    delete row.novoseventos;
  }
  return row;
};

async function execute(sql: string, params: unknown[] = []): Promise<QueryResult<any>> {
  const client = transactionContext.getStore();
  const statement = postgresPlaceholders(sql);
  const result = client
    ? await client.query(statement, params)
    : await pool.query(statement, params);
  result.rows = result.rows.map(normalizeRow);
  return result;
}

export const all = async (sql: string, ...params: any[]) => (await execute(sql, params)).rows;
export const one = async (sql: string, ...params: any[]) => (await execute(sql, params)).rows[0];
export const run = async (sql: string, ...params: any[]) => {
  const result = await execute(sql, params);
  return { changes: result.rowCount || 0, lastInsertRowid: result.rows[0]?.id };
};

export async function transaction<T>(callback: () => Promise<T>): Promise<T> {
  if (transactionContext.getStore()) return callback();
  const client = await pool.connect();
  try {
    await client.query("BEGIN");
    const result = await transactionContext.run(client, callback);
    await client.query("COMMIT");
    return result;
  } catch (error) {
    await client.query("ROLLBACK").catch(() => undefined);
    throw error;
  } finally {
    client.release();
  }
}

export async function initializePostgres(hashPassword: (password: string) => string, options: { bootstrap?: boolean } = {}) {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS users (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      email TEXT NOT NULL UNIQUE,
      name TEXT,
      hash TEXT NOT NULL,
      role TEXT
    );
    CREATE TABLE IF NOT EXISTS organizations (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
    );
    CREATE TABLE IF NOT EXISTS organization_members (
      user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
      organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
      role TEXT NOT NULL CHECK(role IN ('admin','collaborator')),
      status TEXT NOT NULL CHECK(status IN ('active','pending','disabled','blocked')),
      created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
      last_login_at BIGINT,
      UNIQUE(user_id, organization_id)
    );
    CREATE TABLE IF NOT EXISTS permissions(name TEXT PRIMARY KEY, description TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS role_permissions (
      role TEXT NOT NULL CHECK(role IN ('admin','collaborator')),
      permission TEXT NOT NULL REFERENCES permissions(name) ON DELETE CASCADE,
      PRIMARY KEY(role, permission)
    );
    CREATE TABLE IF NOT EXISTS member_permissions (
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      permission TEXT NOT NULL REFERENCES permissions(name) ON DELETE CASCADE,
      granted SMALLINT NOT NULL CHECK(granted IN (0,1)),
      PRIMARY KEY(user_id, permission)
    );
    CREATE TABLE IF NOT EXISTS sessions (
      token TEXT PRIMARY KEY,
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      expires BIGINT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS resets (
      token TEXT PRIMARY KEY,
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      expires BIGINT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS security_audit (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      actor_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
      organization_id BIGINT REFERENCES organizations(id) ON DELETE SET NULL,
      action TEXT NOT NULL,
      target_type TEXT NOT NULL,
      target_id BIGINT,
      created_at BIGINT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS clients (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL, email TEXT, phone TEXT, notes TEXT,
      created_at TEXT DEFAULT CURRENT_TIMESTAMP::text,
      organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
      UNIQUE(id, organization_id)
    );
    CREATE TABLE IF NOT EXISTS events (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL, type TEXT, date TEXT, start_time TEXT,
      client_id BIGINT, contact TEXT, venue TEXT, city TEXT, uf TEXT,
      lineup TEXT, notes TEXT, status TEXT NOT NULL DEFAULT 'rascunho',
      created_at TEXT DEFAULT CURRENT_TIMESTAMP::text,
      updated_at TEXT DEFAULT CURRENT_TIMESTAMP::text,
      end_time TEXT, attire TEXT, crew_arrival TEXT, venue_contact TEXT,
      critical_notes TEXT, contract_value DOUBLE PRECISION,
      organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
      UNIQUE(id, organization_id),
      FOREIGN KEY(client_id, organization_id) REFERENCES clients(id, organization_id) ON DELETE RESTRICT
    );
    CREATE TABLE IF NOT EXISTS finances (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      event_id BIGINT,
      description TEXT NOT NULL,
      amount DOUBLE PRECISION NOT NULL CHECK(amount >= 0),
      due_date TEXT NOT NULL, paid_date TEXT,
      status TEXT NOT NULL DEFAULT 'pendente' CHECK(status IN ('pendente','pago','atrasado','cancelado')),
      installment TEXT,
      created_at TEXT DEFAULT CURRENT_TIMESTAMP::text,
      organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
      FOREIGN KEY(event_id, organization_id) REFERENCES events(id, organization_id) ON DELETE SET NULL (event_id)
    );
    CREATE TABLE IF NOT EXISTS integrantes_equipe (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL, role TEXT NOT NULL, phone TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'ativo', created_at TEXT DEFAULT CURRENT_TIMESTAMP::text,
      organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE
    );
    CREATE TABLE IF NOT EXISTS repertoire (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      event_id BIGINT NOT NULL, moment TEXT NOT NULL,
      position INTEGER NOT NULL DEFAULT 0, title TEXT NOT NULL,
      performer TEXT, notes TEXT, artist TEXT, composer TEXT,
      instrumentation TEXT, reference_url TEXT, owner_user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
      organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
      FOREIGN KEY(event_id, organization_id) REFERENCES events(id, organization_id) ON DELETE CASCADE,
      FOREIGN KEY(owner_user_id, organization_id) REFERENCES organization_members(user_id, organization_id) ON DELETE CASCADE
    );
    CREATE TABLE IF NOT EXISTS repertoire_durations (
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      event_id BIGINT NOT NULL,
      moment TEXT NOT NULL,
      duration_minutes INTEGER NOT NULL CHECK(duration_minutes > 0),
      organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
      PRIMARY KEY(user_id, event_id, moment),
      FOREIGN KEY(event_id, organization_id) REFERENCES events(id, organization_id) ON DELETE CASCADE,
      FOREIGN KEY(user_id, organization_id) REFERENCES organization_members(user_id, organization_id) ON DELETE CASCADE
    );
    CREATE TABLE IF NOT EXISTS repertoire_approvals (
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      event_id BIGINT NOT NULL,
      status TEXT NOT NULL CHECK(status IN ('pendente','aprovado')),
      organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
      PRIMARY KEY(user_id, event_id),
      FOREIGN KEY(event_id, organization_id) REFERENCES events(id, organization_id) ON DELETE CASCADE,
      FOREIGN KEY(user_id, organization_id) REFERENCES organization_members(user_id, organization_id) ON DELETE CASCADE
    );
    CREATE TABLE IF NOT EXISTS company_settings (
      user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
      nome TEXT NOT NULL, exibicao TEXT NOT NULL, email TEXT NOT NULL, telefone TEXT NOT NULL,
      idioma TEXT NOT NULL DEFAULT 'pt-BR', moeda TEXT NOT NULL DEFAULT 'BRL',
      formato TEXT NOT NULL DEFAULT 'dd/mm/aaaa', fuso TEXT NOT NULL DEFAULT 'America/Sao_Paulo',
      novosEventos SMALLINT NOT NULL DEFAULT 1, vencimentos SMALLINT NOT NULL DEFAULT 1,
      escalas SMALLINT NOT NULL DEFAULT 0, updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
      organization_id BIGINT NOT NULL UNIQUE REFERENCES organizations(id) ON DELETE CASCADE,
      FOREIGN KEY(user_id, organization_id) REFERENCES organization_members(user_id, organization_id) ON DELETE CASCADE
    );
    CREATE TABLE IF NOT EXISTS invitations (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
      email TEXT NOT NULL, name TEXT NOT NULL,
      role TEXT NOT NULL CHECK(role='collaborator'),
      target_role TEXT NOT NULL DEFAULT 'collaborator' CHECK(target_role IN ('admin','collaborator')),
      token_hash TEXT NOT NULL UNIQUE, expires_at BIGINT NOT NULL,
      created_by BIGINT NOT NULL REFERENCES users(id), accepted_at BIGINT, created_at BIGINT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS team_members (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL, instrument TEXT, formation TEXT, phone TEXT, notes TEXT,
      available SMALLINT, organization_id BIGINT REFERENCES organizations(id) ON DELETE CASCADE,
      UNIQUE(id, organization_id)
    );
    CREATE TABLE IF NOT EXISTS event_members (
      event_id BIGINT NOT NULL,
      member_id BIGINT NOT NULL,
      organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
      PRIMARY KEY(event_id,member_id),
      FOREIGN KEY(event_id,organization_id) REFERENCES events(id,organization_id) ON DELETE CASCADE,
      FOREIGN KEY(member_id,organization_id) REFERENCES team_members(id,organization_id) ON DELETE CASCADE
    );
    CREATE TABLE IF NOT EXISTS payments (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      event_id BIGINT,
      due_date TEXT, amount DOUBLE PRECISION, installment TEXT, installments INTEGER,
      status TEXT, paid_at TEXT, notes TEXT,
      organization_id BIGINT REFERENCES organizations(id) ON DELETE CASCADE,
      FOREIGN KEY(event_id,organization_id) REFERENCES events(id,organization_id) ON DELETE SET NULL (event_id)
    );
    CREATE INDEX IF NOT EXISTS ev_date ON events(date);
    CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);
    CREATE INDEX IF NOT EXISTS sessions_expiry ON sessions(expires);
    CREATE INDEX IF NOT EXISTS resets_user_expiry ON resets(user_id, expires);
    CREATE INDEX IF NOT EXISTS audit_actor_date ON security_audit(actor_user_id, created_at DESC);
    CREATE INDEX IF NOT EXISTS audit_org_date ON security_audit(organization_id, created_at DESC);
    CREATE INDEX IF NOT EXISTS clients_org_id ON clients(organization_id);
    CREATE INDEX IF NOT EXISTS events_org_id ON events(organization_id);
    CREATE INDEX IF NOT EXISTS integrantes_equipe_org_id ON integrantes_equipe(organization_id);
    CREATE INDEX IF NOT EXISTS fin_event ON finances(event_id);
    CREATE INDEX IF NOT EXISTS fin_due ON finances(due_date);
    CREATE INDEX IF NOT EXISTS fin_status ON finances(status);
    CREATE INDEX IF NOT EXISTS finances_org_id ON finances(organization_id);
    CREATE INDEX IF NOT EXISTS rep_event ON repertoire(event_id);
    CREATE INDEX IF NOT EXISTS rep_owner_event ON repertoire(owner_user_id,event_id);
    CREATE INDEX IF NOT EXISTS repertoire_org_id ON repertoire(organization_id);
    CREATE INDEX IF NOT EXISTS repertoire_durations_org_id ON repertoire_durations(organization_id);
    CREATE INDEX IF NOT EXISTS repertoire_approvals_org_id ON repertoire_approvals(organization_id);
    CREATE INDEX IF NOT EXISTS organization_members_org ON organization_members(organization_id,status);
    CREATE INDEX IF NOT EXISTS invitations_org_expiry ON invitations(organization_id,expires_at);
  `);

  if (options.bootstrap !== false) await transaction(async () => {
    let admin = await one("SELECT id FROM users ORDER BY id LIMIT 1");
    if (!admin && process.env.ADMIN_EMAIL && process.env.ADMIN_PASSWORD) {
      if (process.env.ADMIN_PASSWORD.length < 12 || process.env.ADMIN_PASSWORD.length > 1024)
        throw new Error("ADMIN_PASSWORD deve conter entre 12 e 1024 caracteres na inicialização.");
      admin = await one(
        "INSERT INTO users(email,name,hash) VALUES(?,?,?) RETURNING id",
        process.env.ADMIN_EMAIL.toLowerCase(),
        process.env.ADMIN_NAME || "Administrador",
        hashPassword(process.env.ADMIN_PASSWORD),
      );
    }
    const existingOrganization = await one("SELECT id FROM organizations ORDER BY id LIMIT 1");
    if (!existingOrganization && admin) {
      const organization = await one(
        "INSERT INTO organizations(name) VALUES(?) RETURNING id",
        `${process.env.ADMIN_NAME || "Administrador"} — Organização`,
      );
      await run("INSERT INTO organization_members(user_id,organization_id,role,status) VALUES(?,?,?,?) ON CONFLICT(user_id) DO NOTHING", admin.id, organization.id, "admin", "active");
      await seedPermissions();
    } else if (!existingOrganization && !admin) {
      throw new Error("PostgreSQL está vazio. Configure ADMIN_EMAIL e ADMIN_PASSWORD para criar o administrador inicial.");
    }
    await seedPermissions();
    await run("DELETE FROM sessions WHERE expires<=?", Date.now());
    await run("DELETE FROM resets WHERE expires<=?", Date.now());
    await run("UPDATE finances SET status='atrasado' WHERE status='pendente' AND due_date < to_char(CURRENT_DATE,'YYYY-MM-DD')");
  });
}

const permissionNames = ["users.view","users.create","users.edit","users.disable","users.delete","events.view","events.create","events.edit","events.delete","clients.view","clients.create","clients.edit","clients.delete","finance.view","finance.create","finance.edit","finance.delete","team.view","team.create","team.edit","team.delete","reports.view","repertoire.view","repertoire.edit","settings.view","settings.edit","audit.view"];
const collaboratorPermissions = ["events.view","events.create","events.edit","clients.view","clients.create","clients.edit","team.view","team.create","team.edit","finance.view","reports.view","repertoire.view","settings.view"];
async function seedPermissions() {
  const descriptions: Record<string,string> = {
    "users.view":"Listar colaboradores","users.create":"Convidar colaboradores","users.edit":"Editar colaboradores","users.disable":"Desativar colaboradores","users.delete":"Remover colaboradores",
    "events.view":"Consultar eventos","events.create":"Criar eventos","events.edit":"Editar eventos","events.delete":"Excluir eventos",
    "clients.view":"Consultar clientes","clients.create":"Criar clientes","clients.edit":"Editar clientes","clients.delete":"Excluir clientes",
    "finance.view":"Consultar financeiro","finance.create":"Criar lançamentos","finance.edit":"Editar lançamentos","finance.delete":"Excluir lançamentos",
    "team.view":"Consultar equipe","team.create":"Adicionar equipe","team.edit":"Editar equipe","team.delete":"Remover equipe",
    "reports.view":"Consultar relatórios","repertoire.view":"Consultar repertório","repertoire.edit":"Editar repertório","settings.view":"Consultar configurações","settings.edit":"Editar configurações","audit.view":"Consultar auditoria",
  };
  for (const permission of permissionNames) {
    await run("INSERT INTO permissions(name,description) VALUES(?,?) ON CONFLICT(name) DO NOTHING", permission, descriptions[permission]);
    await run("INSERT INTO role_permissions(role,permission) VALUES('admin',?) ON CONFLICT DO NOTHING", permission);
  }
  for (const permission of collaboratorPermissions)
    await run("INSERT INTO role_permissions(role,permission) VALUES('collaborator',?) ON CONFLICT DO NOTHING", permission);
}

export async function closeDatabase() {
  await pool.end();
}
